def restore_capitalization(text: str) -> str:
    """
    Восстановление заглавных букв

    - После точки, вопроса, восклицания
    - В начале текста
    - После переноса строки
    """
    if not text:
        return text

    # Первая буква текста - заглавная
    result = []
    capitalize_next = True

    i = 0
    while i < len(text):
        char = text[i]

        if char in '.!?\n':
            result.append(char)
            capitalize_next = True
        elif capitalize_next and char.isalpha():
            result.append(char.upper())
            capitalize_next = False
        else:
            result.append(char)
            if not char.isspace():
                capitalize_next = False

        i += 1

    return ''.join(result)


def restore_punctuation(text: str, language: str = 'ru') -> str:
    """
    Базовое восстановление пунктуации

    Использует эвристики:
    - Вводные слова -> запятая после них
    - Вопросительные слова в начале -> вопрос в конце
    - Короткие фразы типа "да", "нет" -> точка или запятая
    """
    if not text:
        return text

    # Разбиваем на предложения (или предполагаемые предложения)
    # Если нет знаков препинания - пытаемся восстановить

    # Проверяем, есть ли уже пунктуация
    has_punctuation = bool(re.search(r'[.!?]', text))
    if has_punctuation:
        return text

    sentences = []
    words = text.split()

    if not words:
        return text

    current_sentence = []

    for i, word in enumerate(words):
        current_sentence.append(word)
        word_lower = word.lower().strip('.,!?')

        # Проверяем, нужно ли завершить предложение
        should_end = False
        end_mark = '.'

        # Вопросительные слова в начале предложения
        if len(current_sentence) >= 3:
            first_word = current_sentence[0].lower()
            if first_word in {'что', 'как', 'где', 'когда', 'почему', 'зачем', 'кто', 'какой', 'какая', 'какое', 'сколько', 'куда', 'откуда'}:
                # Проверяем, похоже ли на конец вопроса
                if word_lower in SENTENCE_END_WORDS or i == len(words) - 1:
                    should_end = True
                    end_mark = '?'

        # Короткие фразы-подтверждения
        if word_lower in SENTENCE_END_WORDS and len(current_sentence) <= 3:
            should_end = True

        # Длинное предложение без пауз (>20 слов) - разбиваем
        if len(current_sentence) > 20:
            # Ищем хорошее место для разрыва
            if word_lower in {'и', 'но', 'а', 'или', 'потому', 'поэтому', 'однако'}:
                should_end = True

        if should_end and current_sentence:
            sentence_text = ' '.join(current_sentence)
            if not sentence_text.endswith(('.', '!', '?')):
                sentence_text += end_mark
            sentences.append(sentence_text)
            current_sentence = []

    # Добавляем оставшееся
    if current_sentence:
        sentence_text = ' '.join(current_sentence)
        if not sentence_text.endswith(('.', '!', '?')):
            sentence_text += '.'
        sentences.append(sentence_text)

    result = ' '.join(sentences)

    # Добавляем запятые после вводных слов
    for intro_word in INTRODUCTORY_WORDS:
        pattern = rf'\b({re.escape(intro_word)})\s+'
        result = re.sub(pattern, rf'\1, ', result, flags=re.IGNORECASE)

    return result


def convert_numbers(text: str) -> str:
    """
    Преобразование числительных в цифры

    "двадцать один" -> "21"
    "пять тысяч" -> "5000"
    """
    if not text:
        return text

    result = text

    # Сначала обрабатываем простые числительные
    for word, number in sorted(NUMBERS_WORDS_RU.items(), key=lambda x: -len(x[0])):
        pattern = rf'\b{re.escape(word)}\b'
        result = re.sub(pattern, number, result, flags=re.IGNORECASE)

    # Обрабатываем составные числительные
    for pattern, replacement in COMPOUND_NUMBER_PATTERNS:
        if replacement:
            result = re.sub(pattern, replacement, result, flags=re.IGNORECASE)

    return result


def fix_asr_errors(text: str) -> str:
    """
    Исправление типичных ошибок ASR

    - Слитные слова
    - Фонетические искажения
    - Повторы
    - IT-термины
    """
    if not text:
        return text

    result = text

    # Применяем словарные замены (от длинных к коротким)
    for error, correction in sorted(ASR_CORRECTIONS_RU.items(), key=lambda x: -len(x[0])):
        pattern = rf'\b{re.escape(error)}\b'
        result = re.sub(pattern, correction, result, flags=re.IGNORECASE)

    # Применяем паттерны регулярных выражений
    for pattern, replacement in ASR_CORRECTION_PATTERNS:
        result = re.sub(pattern, replacement, result)

    return result


def clean_repetitions(text: str) -> str:
    """
    Удаление повторений слов и символов

    "да да да" -> "да"
    "ааааа" -> "а"
    """
    if not text:
        return text

    result = text

    # Удаляем повторяющиеся символы (больше 2)
    result = re.sub(r'(.)\1{2,}', r'\1\1', result)

    # Удаляем повторяющиеся слова
    result = re.sub(r'\b(\w+)(\s+\1){2,}\b', r'\1', result, flags=re.IGNORECASE)

    # Удаляем двойные повторения
    result = re.sub(r'\b(\w+)\s+\1\b', r'\1', result, flags=re.IGNORECASE)

    return result


def normalize_whitespace(text: str) -> str:
    """Нормализация пробелов и переносов"""
    if not text:
        return text

    # Удаляем множественные пробелы
    text = re.sub(r' +', ' ', text)

    # Удаляем пробелы в начале и конце строк
    text = '\n'.join(line.strip() for line in text.split('\n'))

    # Удаляем множественные переносы строк
    text = re.sub(r'\n{3,}', '\n\n', text)

    return text.strip()


def post_process_text(text: str, language: str = 'ru', options: Optional[dict] = None) -> str:
    """
    Полная постобработка текста

    Args:
        text: Исходный текст
        language: Язык текста ('ru', 'en', 'auto')
        options: Опции обработки:
            - fix_case: bool - восстанавливать регистр (default: True)
            - fix_punctuation: bool - восстанавливать пунктуацию (default: True)
            - convert_numbers: bool - преобразовывать числительные (default: True)
            - fix_asr: bool - исправлять ошибки ASR (default: True)
            - clean_repetitions: bool - удалять повторения (default: True)

    Returns:
        str: Обработанный текст
    """
    if not text:
        return text

    opts = options or {}
    do_fix_case = opts.get('fix_case', True)
    do_fix_punctuation = opts.get('fix_punctuation', True)
    do_convert_numbers = opts.get('convert_numbers', True)
    do_fix_asr = opts.get('fix_asr', True)
    do_clean_repetitions = opts.get('clean_repetitions', True)

    result = text

    # 1. Удаляем повторения (первичная очистка)
    if do_clean_repetitions:
        result = clean_repetitions(result)

    # 2. Исправляем ошибки ASR
    if do_fix_asr and language in ('ru', 'auto'):
        result = fix_asr_errors(result)

    # 3. Преобразуем числительные
    if do_convert_numbers and language in ('ru', 'auto'):
        result = convert_numbers(result)

    # 4. Восстанавливаем пунктуацию
    if do_fix_punctuation:
        result = restore_punctuation(result, language)

    # 5. Восстанавливаем регистр
    if do_fix_case:
        result = restore_capitalization(result)

    # 6. Финальная нормализация пробелов
    result = normalize_whitespace(result)

    return result


def process_segment(segment_text: str, language: str = 'ru') -> str:
    """
    Обработка отдельного сегмента (быстрая версия)

    Для обработки во время транскрибации - только базовые исправления
    """
    if not segment_text:
        return segment_text

    result = segment_text

    # Быстрые исправления
    result = clean_repetitions(result)
    result = fix_asr_errors(result)
    result = normalize_whitespace(result)

    return result
